-- ============================================================================
-- 거래명세서 전용 안내문구 칸
--
-- **왜 필요한가** — 거래명세서 아래에 견적서 문구(`quote_terms`)가 그대로
-- 인쇄되고 있었다: "본 견적은 발행일로부터 유효기간 내에만 유효합니다."
-- 이미 납품한 물건의 명세서인데 견적이라고 적히고, "부가세 별도"라고 하면서
-- 정작 그 문서는 부가세를 더해 합계를 낸다. 고객이 받아 보는 문서다.
--
-- 이 칸이 없어도 앱은 그대로 동작한다 — 없으면 기본 문장
-- ('위와 같이 거래하였음을 확인합니다.')을 쓴다. 이 SQL은 그 문구를
-- 설정 화면에서 고치고 싶을 때만 돌리면 된다.
--
-- 몇 번을 다시 돌려도 안전하다.
-- ============================================================================

alter table public.company_profile
    add column if not exists statement_terms text;

comment on column public.company_profile.statement_terms is
    '거래명세서 하단 안내문구. 비어 있으면 앱이 기본 문장을 쓴다.';

-- 확인
select statement_terms from public.company_profile limit 1;
